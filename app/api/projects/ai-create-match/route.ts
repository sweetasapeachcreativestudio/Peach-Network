import { NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";
import { createAdminClient } from "@/lib/supabase/admin";

export async function POST(request: Request) {
  try {
    const supabase = await createClient();
    const {
      data: { user },
    } = await supabase.auth.getUser();

    if (!user) {
      return NextResponse.json({ error: "Sign in required." }, { status: 401 });
    }

    const admin = createAdminClient();
    const { data: business } = await admin
      .from("businesses")
      .select("id,name")
      .eq("owner_user_id", user.id)
      .maybeSingle();

    if (!business) {
      return NextResponse.json(
        { error: "Business account required to commission a project." },
        { status: 403 }
      );
    }

    const body = await request.json();
    const coins = Math.max(1, Number(body.coins) || 2);
    const deliverablesList = Array.isArray(body.deliverables)
      ? body.deliverables.map((d: string) => `• ${d}`).join("\n")
      : "• Commercial production-ready source assets\n• Web & print exports\n• Commercial usage rights release";

    const requiredBusinessList = Array.isArray(body.requiredFromBusiness) && body.requiredFromBusiness.length > 0
      ? body.requiredFromBusiness.map((r: string) => `• ${r}`).join("\n")
      : "• Brand assets, high-res logo files, and style preferences\n• Finalized text/copy and necessary logins/credentials\n• Timely review and milestone feedback";

    // 1. Build the official Creative Brief Sheet & Contract
    const creativeBriefSheet = `# 🍑 OFFICIAL CREATIVE BRIEF SHEET & SCOPE CONTRACT
**Project**: ${body.title || "Custom Commercial Project"}
**Client**: ${business.name}
**Category**: ${body.category || "Design"}
**2026 Master Budget**: ${coins} Peach Coins ($${coins * 50} USD held in protected escrow)
**Turnaround Timeline**: ${body.estimatedTurnaround || "3–5 business days"}
**Revisions Included**: 3 Full Revision Rounds (100% money-back or dispute protection)
**Asset & Site Ownership**: 100% administrative transfer to ${business.name} upon completion

---

### 1. Project Objective & Scope of Work
${body.title || "Commercial Design Deliverable"}
${body.scopeSummary || "High-impact commercial deliverable designed to agency standards."}

### 2. Tangible Included Deliverables
${deliverablesList}

### 3. What is Required From the Business
${requiredBusinessList}

### 4. Mutual Contract Terms & Escrow Milestones
1. **Protected Escrow**: The client's ${coins} Peach Coins ($${coins * 50} USD) are locked in secure escrow. Payout occurs only after final milestone approval.
2. **Dual Digital Signatures**: Both the client (${business.name}) and the assigned creative must digitally sign this brief contract before work officially commences.
3. **Turnaround & Proofs**: The creative guarantees first proof delivery within ${body.estimatedTurnaround || "3–5 business days"}.
4. **Included Revisions**: 3 complete revision rounds are included in this contract. Additional revisions can be added at 1 Peach Coin each.
5. **Full Commercial Rights**: 100% intellectual property, vector artwork, and administrative accounts transfer to the business upon project completion.

---
*Generated by Peach Match AI for ${business.name}. Please digitally sign below to begin.*`;

    // 2. Create project with offer_sent status
    const { data: project, error: projErr } = await admin
      .from("projects")
      .insert({
        business_id: business.id,
        title: body.title || "Custom Commercial Project",
        category: body.category || "Design",
        description: creativeBriefSheet,
        status: "offer_sent",
        coin_amount: coins,
        revision_rounds: 3,
        current_revision_round: 0,
        assigned_creative_id: body.selectedCreativeId || null,
        due_at: body.dueAt || new Date(Date.now() + 7 * 86400000).toISOString(),
      })
      .select("*")
      .single();

    if (projErr || !project) {
      console.error("Project creation error:", projErr);
      return NextResponse.json(
        { error: projErr?.message || "Could not initialize project." },
        { status: 500 }
      );
    }

    // 3. Put coins in escrow if available
    const { data: wallet } = await admin
      .from("coin_wallets")
      .select("available_coins,held_coins")
      .eq("business_id", business.id)
      .maybeSingle();

    if (wallet && wallet.available_coins >= coins) {
      await admin
        .from("coin_wallets")
        .update({
          available_coins: wallet.available_coins - coins,
          held_coins: (wallet.held_coins || 0) + coins,
        })
        .eq("business_id", business.id);

      await admin.from("coin_transactions").insert({
        business_id: business.id,
        project_id: project.id,
        amount: -coins,
        transaction_type: "escrow_hold",
        description: `Held ${coins} Peach Coins in escrow for project "${project.title}"`,
      });
    }

    // 4. Create project offer for chosen creative (24-hour clock)
    if (body.selectedCreativeId) {
      const payoutCents = Math.round(coins * 5000 * 0.75); // 75% creative payout
      const expiresAt = new Date(Date.now() + 24 * 60 * 60 * 1000).toISOString();

      await admin.from("project_offers").insert({
        project_id: project.id,
        creative_id: body.selectedCreativeId,
        status: "sent",
        payout_cents: payoutCents,
        expires_at: expiresAt,
      });

      // Record in shortlist
      await admin.from("project_match_shortlists").insert({
        project_id: project.id,
        creative_id: body.selectedCreativeId,
        match_score: Number(body.matchScore) || 98,
        match_reason: body.matchReason || "Selected via Peach Match AI based on verified design history",
        batch_number: 1,
        status: "requested",
      });
    }

    // 5. REQUIREMENT: Put Creative Brief Sheet & Contract directly in the message area!
    await admin.from("project_messages").insert({
      project_id: project.id,
      sender_user_id: user.id,
      message: creativeBriefSheet,
    });

    // Follow-up status note
    await admin.from("project_messages").insert({
      project_id: project.id,
      sender_user_id: user.id,
      message: `Peach Match AI initialized this project. ${coins} Peach Coins ($${coins * 50} USD) are secured in protected escrow. Both parties must review the Creative Brief Sheet above and digitally sign to activate milestones and begin work!`,
    });

    await admin.from("audit_log").insert({
      actor_user_id: user.id,
      action: "project_created_via_peach_match_ai",
      entity_type: "project",
      entity_id: project.id,
      metadata: {
        coins,
        selected_creative: body.selectedCreativeId,
        title: project.title,
        has_creative_brief_sheet: true,
      },
    });

    return NextResponse.json({
      ok: true,
      project: {
        id: project.id,
        title: project.title,
        status: project.status,
      },
    });
  } catch (err: any) {
    console.error("ai-create-match error:", err);
    return NextResponse.json(
      { error: err.message || "Failed to process project match." },
      { status: 500 }
    );
  }
}
